from flask import Flask, render_template, request, jsonify
from datetime import datetime
from uuid import uuid4
from collections import deque
from threading import Lock

app = Flask(__name__)

reminders = []
last_announcement = None

# Pending announcements for the ESP32 demo.
announcement_queue = deque()
queue_lock = Lock()
data_lock = Lock()

SUPPORTED_LANGUAGES = ["en", "hi", "mr"]
MAX_ANNOUNCEMENT_LENGTH = 500


def current_time():
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")


@app.route("/")
def home():
    return render_template("index.html")


@app.route("/api/status", methods=["GET"])
def get_status():
    with queue_lock:
        pending_count = len(announcement_queue)

    with data_lock:
        latest = last_announcement.copy() if last_announcement else None

    return jsonify({
        "online": True,
        "server": "Flask HTTP Server",
        "rtcOk": False,
        "ttsLanguages": [],
        "speechMode": "simulation_only",
        "lastAnnouncement": latest,
        "pendingAnnouncements": pending_count
    })


@app.route("/api/announce", methods=["POST"])
def announce():
    global last_announcement

    data = request.get_json(silent=True) or {}

    text = str(data.get("text", "")).strip()
    language = data.get("language", "")

    if not text:
        return jsonify({
            "success": False,
            "message": "Please enter announcement text."
        }), 400

    if len(text) > MAX_ANNOUNCEMENT_LENGTH:
        return jsonify({
            "success": False,
            "message": "Announcement must be 500 characters or less."
        }), 400

    if language not in SUPPORTED_LANGUAGES:
        return jsonify({
            "success": False,
            "message": "Select a valid language."
        }), 400

    announcement = {
        "id": str(uuid4())[:8],
        "text": text,
        "language": language,
        "time": current_time()
    }

    # Save the latest announcement.
    with data_lock:
        last_announcement = announcement.copy()

    # Add it to the queue for the ESP32.
    with queue_lock:
        announcement_queue.append(announcement.copy())

    return jsonify({
        "success": True,
        "message": (
            "Announcement queued for the ESP32 simulation. "
            "No real speech was generated by the server."
        ),
        "announcement": announcement,
        "simulated": True
    })


@app.route("/api/next-announcement", methods=["GET"])
def next_announcement():
    # The ESP32 receives and removes one queued announcement.
    with queue_lock:
        if announcement_queue:
            announcement = announcement_queue.popleft()

            return jsonify({
                "success": True,
                "available": True,
                "announcement": announcement
            })

    return jsonify({
        "success": True,
        "available": False
    })


@app.route("/api/reminders", methods=["GET"])
def get_reminders():
    search = request.args.get("search", "").strip().lower()

    with data_lock:
        results = [
            reminder.copy()
            for reminder in reminders
            if search in reminder["medicineName"].lower()
            or search in reminder["language"].lower()
        ]

    return jsonify({
        "success": True,
        "reminders": results
    })


@app.route("/api/reminders", methods=["POST"])
def add_reminder():
    data = request.get_json(silent=True) or {}

    name = str(data.get("medicineName", "")).strip()
    time_value = str(data.get("time", "")).strip()
    language = data.get("language", "en")
    repeat = data.get("repeat", "daily")

    if not name or len(name) > 100:
        return jsonify({
            "success": False,
            "message": "Medicine name is required (maximum 100 characters)."
        }), 400

    try:
        datetime.strptime(time_value, "%H:%M")
    except ValueError:
        return jsonify({
            "success": False,
            "message": "Enter a valid time."
        }), 400

    if language not in SUPPORTED_LANGUAGES:
        return jsonify({
            "success": False,
            "message": "Select a valid language."
        }), 400

    if repeat not in ["daily", "once"]:
        return jsonify({
            "success": False,
            "message": "Select a valid repeat option."
        }), 400

    reminder = {
        "id": str(uuid4())[:8],
        "medicineName": name,
        "time": time_value,
        "language": language,
        "repeat": repeat
    }

    with data_lock:
        reminders.append(reminder.copy())

    return jsonify({
        "success": True,
        "message": "Reminder saved in mock server memory.",
        "reminder": reminder
    }), 201


@app.route("/api/reminders/<reminder_id>", methods=["PUT"])
def update_reminder(reminder_id):
    data = request.get_json(silent=True) or {}

    name = str(data.get("medicineName", "")).strip()
    time_value = str(data.get("time", "")).strip()
    language = data.get("language", "en")
    repeat = data.get("repeat", "daily")

    if not name or len(name) > 100:
        return jsonify({
            "success": False,
            "message": "Medicine name is required (maximum 100 characters)."
        }), 400

    try:
        datetime.strptime(time_value, "%H:%M")
    except ValueError:
        return jsonify({
            "success": False,
            "message": "Enter a valid time."
        }), 400

    if language not in SUPPORTED_LANGUAGES:
        return jsonify({
            "success": False,
            "message": "Select a valid language."
        }), 400

    if repeat not in ["daily", "once"]:
        return jsonify({
            "success": False,
            "message": "Select a valid repeat option."
        }), 400

    with data_lock:
        for reminder in reminders:
            if reminder["id"] == reminder_id:
                reminder.update({
                    "medicineName": name,
                    "time": time_value,
                    "language": language,
                    "repeat": repeat
                })

                updated = reminder.copy()
                break
        else:
            updated = None

    if updated is None:
        return jsonify({
            "success": False,
            "message": "Reminder not found."
        }), 404

    return jsonify({
        "success": True,
        "message": "Reminder updated.",
        "reminder": updated
    })


@app.route("/api/reminders/<reminder_id>", methods=["DELETE"])
def delete_reminder(reminder_id):
    with data_lock:
        for index, reminder in enumerate(reminders):
            if reminder["id"] == reminder_id:
                reminders.pop(index)
                break
        else:
            return jsonify({
                "success": False,
                "message": "Reminder not found."
            }), 404

    return jsonify({
        "success": True,
        "message": "Reminder deleted."
    })


if __name__ == "__main__":
    app.run(host="0.0.0.0", port=5000, debug=False)